import uuid

from django.conf import settings
from django.db import models


class FilePurpose(models.TextChoices):
    COMPANY_LOGO = "company_logo", "Company logo"
    BRANDING_SIGNATURE = "branding_signature", "Authorised signature"
    BRANDING_SEAL = "branding_seal", "Company seal"


class StoredFile(models.Model):
    """An immutable file in private storage.

    Content never changes after upload; replacing an asset creates a new
    StoredFile, so historical records (e.g. published branding versions) keep
    pointing at exactly what they used. The storage path is generated by the
    server and never derived from the client's filename.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    purpose = models.CharField(max_length=32, choices=FilePurpose.choices, db_index=True)
    storage_name = models.CharField(max_length=255, unique=True, editable=False)
    original_name = models.CharField(max_length=120, blank=True)
    content_type = models.CharField(max_length=64)
    size = models.PositiveIntegerField()
    sha256 = models.CharField(max_length=64)
    width = models.PositiveIntegerField(null=True, blank=True)
    height = models.PositiveIntegerField(null=True, blank=True)
    uploaded_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, on_delete=models.PROTECT, related_name="+"
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self) -> str:
        return f"{self.get_purpose_display()} · {self.original_name or self.id}"
